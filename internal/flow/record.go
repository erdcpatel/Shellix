package flow

import (
	"bufio"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"shellix/internal/core"

	"github.com/charmbracelet/lipgloss"
	"gopkg.in/yaml.v3"
)

// RecordedCommand captures an executed command in a recording session
type RecordedCommand struct {
	Command    string        `json:"command"`
	WorkingDir string        `json:"working_dir"`
	ExitCode   int           `json:"exit_code"`
	Duration   time.Duration `json:"duration"`
	Timestamp  time.Time     `json:"timestamp"`
}

// RecordSession stores the complete recorded session history
type RecordSession struct {
	FlowName    string            `json:"flow_name"`
	Description string            `json:"description"`
	Commands    []RecordedCommand `json:"commands"`
	StartTime   time.Time         `json:"start_time"`
	EndTime     time.Time         `json:"end_time"`
}

// SynthesizeStepName creates clean, idiomatic step names from shell command strings
func SynthesizeStepName(rawCmd string, index int) string {
	clean := strings.TrimSpace(rawCmd)
	if clean == "" {
		return fmt.Sprintf("step-%d", index+1)
	}

	parts := strings.Fields(clean)
	bin := filepath.Base(parts[0])

	switch bin {
	case "go":
		if len(parts) > 1 {
			switch parts[1] {
			case "test":
				return "run-go-tests"
			case "build":
				return "build-go-binary"
			case "vet":
				return "vet-go-code"
			case "mod":
				return "tidy-go-modules"
			}
		}
		return "go-command"
	case "make":
		if len(parts) > 1 {
			return "make-" + parts[1]
		}
		return "make-build"
	case "npm", "yarn", "pnpm":
		if len(parts) > 1 {
			return parts[0] + "-" + parts[1]
		}
		return parts[0] + "-run"
	case "mvn", "gradle", "gradlew":
		return "java-build"
	case "docker":
		if len(parts) > 1 {
			return "docker-" + parts[1]
		}
		return "docker-op"
	case "curl", "wget":
		return "http-request"
	case "git":
		if len(parts) > 1 {
			return "git-" + parts[1]
		}
		return "git-op"
	}

	// Fallback: sanitize command string into alphanumeric slug
	reg := regexp.MustCompile(`[^a-zA-Z0-9]+`)
	slug := reg.ReplaceAllString(bin, "-")
	slug = strings.Trim(slug, "-")
	if slug == "" {
		slug = "step"
	}
	return fmt.Sprintf("%s-%d", slug, index+1)
}

// SynthesizeFlowYAML converts recorded commands into a declarative Shellix Flow YAML
func SynthesizeFlowYAML(session RecordSession) (string, error) {
	if session.FlowName == "" {
		session.FlowName = "recorded-workflow"
	}
	if session.Description == "" {
		session.Description = fmt.Sprintf("Recorded workflow generated by Shellix on %s", time.Now().Format("2006-01-02"))
	}

	f := Flow{
		Name:        session.FlowName,
		Description: session.Description,
		Steps:       make([]Step, 0, len(session.Commands)),
	}

	usedNames := make(map[string]int)

	for i, c := range session.Commands {
		cmdStr := strings.TrimSpace(c.Command)
		if cmdStr == "" {
			continue
		}

		// Security: sanitize any secret tokens before writing to YAML
		cmdStr = core.GlobalSanitizer.Sanitize(cmdStr)

		baseName := SynthesizeStepName(cmdStr, i)
		stepName := baseName
		if count, exists := usedNames[baseName]; exists {
			usedNames[baseName] = count + 1
			stepName = fmt.Sprintf("%s-%d", baseName, count+1)
		} else {
			usedNames[baseName] = 1
		}

		// Calculate timeout with a generous safety buffer based on recorded duration
		timeout := "2m"
		if c.Duration > 0 {
			buffered := c.Duration*3 + 10*time.Second
			if buffered < 30*time.Second {
				timeout = "1m"
			} else if buffered < 5*time.Minute {
				timeout = fmt.Sprintf("%dm", int(buffered.Minutes())+1)
			} else {
				timeout = "10m"
			}
		}

		step := Step{
			Name:      stepName,
			Run:       cmdStr,
			Timeout:   timeout,
			OnFailure: "abort",
		}
		f.Steps = append(f.Steps, step)
	}

	data, err := yaml.Marshal(&f)
	if err != nil {
		return "", fmt.Errorf("failed to encode flow YAML: %w", err)
	}

	return string(data), nil
}

// RunInteractiveRecorder prompts the user for commands, runs them live, and saves the workflow YAML
func RunInteractiveRecorder(flowName, saveDir string) (string, error) {
	if flowName == "" {
		flowName = fmt.Sprintf("flow-%d", time.Now().Unix())
	}
	if saveDir == "" {
		saveDir = filepath.Join(".", ".shellix", "flows")
		_ = os.MkdirAll(saveDir, 0700)
	}

	titleStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("#7D56F4"))
	recordStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("#FF4500"))
	metaStyle := lipgloss.NewStyle().Foreground(lipgloss.Color("#888888"))
	promptStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("#00BFFF"))
	successStyle := lipgloss.NewStyle().Bold(true).Foreground(lipgloss.Color("#04B575"))

	fmt.Printf("%s Starting Workflow Recording: %s\n",
		recordStyle.Render("🔴 [RECORDER]"), titleStyle.Render(flowName))
	fmt.Println(metaStyle.Render("Type your commands below. Each command will execute live."))
	fmt.Println(metaStyle.Render("Type 'done' or 'exit' when finished to synthesize YAML.\n"))

	scanner := bufio.NewScanner(os.Stdin)
	var commands []RecordedCommand
	startTime := time.Now()

	for {
		fmt.Printf("%s ", promptStyle.Render(fmt.Sprintf("[rec:%s]$", flowName)))
		if !scanner.Scan() {
			break
		}
		line := strings.TrimSpace(scanner.Text())
		if line == "" {
			continue
		}
		if line == "done" || line == "exit" || line == "quit" {
			break
		}

		// Execute live
		cwd, _ := os.Getwd()
		cmdStart := time.Now()

		c := exec.Command("bash", "-c", line)
		c.Stdin = os.Stdin
		c.Stdout = os.Stdout
		c.Stderr = os.Stderr

		runErr := c.Run()
		dur := time.Since(cmdStart)
		exitCode := 0
		if runErr != nil {
			exitCode = 1
			if exitErr, ok := runErr.(*exec.ExitError); ok {
				exitCode = exitErr.ExitCode()
			}
		}

		commands = append(commands, RecordedCommand{
			Command:    line,
			WorkingDir: cwd,
			ExitCode:   exitCode,
			Duration:   dur,
			Timestamp:  cmdStart,
		})

		fmt.Printf("   %s (%s)\n\n",
			metaStyle.Render(fmt.Sprintf("Step %d recorded", len(commands))),
			dur.Round(time.Millisecond).String())
	}

	if len(commands) == 0 {
		return "", fmt.Errorf("no commands were recorded. Flow creation aborted")
	}

	session := RecordSession{
		FlowName:  flowName,
		Commands:  commands,
		StartTime: startTime,
		EndTime:   time.Now(),
	}

	yamlContent, err := SynthesizeFlowYAML(session)
	if err != nil {
		return "", err
	}

	targetFile := filepath.Join(saveDir, flowName+".yaml")
	if err := os.WriteFile(targetFile, []byte(yamlContent), 0600); err != nil {
		return "", fmt.Errorf("failed to write flow file: %w", err)
	}

	fmt.Printf("\n%s Successfully synthesized %d steps into: %s\n",
		successStyle.Render("✨ [FLOW SYNTHESIZED]"), len(commands), targetFile)
	fmt.Printf("Run your new flow with: sx flow run %s --tui\n\n", flowName)

	return targetFile, nil
}
